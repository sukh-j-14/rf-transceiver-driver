'use strict';
const assert = require('node:assert/strict');
const Radio = require('./model.js');
let checks = 0;
function check(actual, expected) { assert.deepEqual(actual, expected); checks++; }
const r = new Radio();
check(r.send([1],3),'STATE');
check(r.tune(900000),'STATE');
check(r.init(0),'INVALID');
check(r.init(2),'TIMEOUT');
check(r.initialized,false);
check(r.init(3),'OK');
check(r.polls,3);
check(r.send([1],3),'STATE');
for (const frequency of [699999,6000001,NaN,700000.5]) check(r.tune(frequency),'INVALID');
for (const frequency of [700000,6000000,3500000]) check(r.tune(frequency),'OK');
for (const payload of [[],Array(65).fill(1),[256],[-1],[1.5]]) check(r.send(payload,3),'INVALID');
check(r.send([1],0),'INVALID');
check(r.send([1,2,3,255],3),'OK');
check(r.payload,[1,2,3,255]);
check(r.send([1],2),'TIMEOUT');
check(r.polls,2);
check(r.send([1],3),'OK');
r.fail=true;
check(r.tune(900000),'IO');
check(r.frequency,3500000);
check(r.send([1],3),'IO');
check(r.init(3),'IO');
check(r.initialized,false);
r.fail=false;r.stuck=true;
check(r.init(3),'TIMEOUT');
r.stuck=false;
check(r.init(3),'OK');
check(r.frequency,0);
check(r.payload,[]);
check(r.tune(900000),'OK');
check(r.send(Array(64).fill(255),3),'OK');
check(r.payload.length,64);
check(r.send([42],3),'OK');
check(r.payload,[42]);
r.registers[0]=0;
check(r.init(3),'INVALID');
check(r.initialized,false);
r.reset();
check(r.registers,[0x5246,0,0,0,0]);
check(r.fail,false);
check(r.stuck,false);
console.log(`PASS ${checks} JavaScript teaching-model checks`);
